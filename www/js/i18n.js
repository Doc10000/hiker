let LANG = 'ru';

function langName(code) {
  const l = LANGS.find(x => x.code === code);
  return l ? l.name : 'Русский';
}

/** Перевод динамической строки (уровень, категория риска) */
function tr(s) {
  if (LANG === 'ru') return s;
  const d = I18N_DYN[LANG];
  return (d && d[s]) || s;
}

/** Перевод статической строки по русскому ключу */
function tk(s) {
  if (LANG === 'ru') return s;
  const d = I18N[LANG];
  return (d && d[s]) || s;
}

/**
 * Точный перевод, иначе — подстановка русских фрагментов.
 * Покрывает и статичные строки, и динамические (шаблоны с ${...}),
 * потому что куски шаблонов тоже лежат в словаре.
 */
const _fragKeys = {};
function translateText(s, dict) {
  if (!dict) return s;
  const exact = dict[s];
  if (exact !== undefined) return exact;
  let keys = _fragKeys[LANG];
  if (!keys) {
    keys = Object.keys(dict).filter(k => k.length >= 2)
      .sort((a, b) => b.length - a.length);
    _fragKeys[LANG] = keys;
  }
  let out = s;
  for (const k of keys) {
    if (out.indexOf(k) !== -1) out = out.split(k).join(dict[k]);
  }
  return out;
}

/**
 * Проходит по текстовым узлам и подставляет перевод.
 * Оригинал запоминается один раз — можно вернуться на русский.
 */
function applyI18n() {
  document.documentElement.lang = LANG;
  const dict = LANG === 'ru' ? null : I18N[LANG];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);

  for (const node of nodes) {
    const raw = node.nodeValue;
    const key = raw.trim();
    if (!key) continue;
    const parent = node.parentElement;
    if (parent && (parent.closest('script, style, pre, code, .code'))) continue;
    if (node._src === undefined) node._src = raw;
    const src = node._src;
    const srcKey = src.trim();
    if (!dict) { node.nodeValue = src; continue; }          // возврат на русский
    const out = translateText(srcKey, dict);
    if (out !== srcKey) node.nodeValue = out;
  }

  // плейсхолдеры
  document.querySelectorAll('input[placeholder]').forEach(inp => {
    if (inp._srcPh === undefined) inp._srcPh = inp.getAttribute('placeholder') || '';
    const src = inp._srcPh.trim();
    inp.setAttribute('placeholder', !dict ? inp._srcPh : translateText(src, dict));
  });

  renderLangList();
}

function setLang(code) {
  LANG = LANGS.some(l => l.code === code) ? code : 'ru';
  try { localStorage.setItem('lang', LANG); } catch (e) {}
  applyI18n();
}

function initLang() {
  let saved = 'ru';
  try { saved = localStorage.getItem('lang') || 'ru'; } catch (e) {}
  LANG = LANGS.some(l => l.code === saved) ? saved : 'ru';
}

/** Список языков с флагами (экран «Ещё») */
function renderLangList() {
  const html = LANGS.map(l => `
    <button class="lang-item ${l.code === LANG ? 'sel' : ''}" data-lang="${l.code}">
      <span class="lang-flag">${l.flag}</span>
      <span class="lang-name">${l.name}</span>
      <span class="lang-code">${l.code.toUpperCase()}</span>
    </button>`).join('');
  // два места: первый экран выбора языка и раздел «Ещё»
  ['lang-list-start', 'lang-list'].forEach(id => {
    const box = document.getElementById(id);
    if (box) box.innerHTML = html;
  });
}
